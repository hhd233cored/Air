-- 第 0 阶段只建立后续学习会用到的最小数据结构，不代表最终业务模型。
-- 生产默认只执行此结构迁移；本地演示数据位于单独的 fixtures 目录。

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    -- 只存 Argon2id 密码哈希；应用不会保存明文密码。
    password_hash TEXT NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('USER', 'ADMIN')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    avatar_data BYTEA,
    avatar_content_type VARCHAR(64),
    avatar_updated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

-- Python 服务的用户名比较不区分大小写；索引在 PostgreSQL 中明确保留这一规则。
CREATE UNIQUE INDEX users_username_lower_unique ON users (LOWER(username));

CREATE TABLE content_items (
    id VARCHAR(80) PRIMARY KEY,
    content_type VARCHAR(16) NOT NULL CHECK (content_type IN ('ARTICLE', 'CHATTER')),
    slug VARCHAR(180) NOT NULL,
    title TEXT,
    summary TEXT,
    preview TEXT,
    cover_url TEXT,
    cover_color VARCHAR(32),
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    status VARCHAR(16) NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    content_markdown TEXT NOT NULL,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT content_items_type_slug_unique UNIQUE (content_type, slug)
);

CREATE INDEX content_items_type_status_published_idx
    ON content_items (content_type, status, published_at DESC);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type VARCHAR(16) NOT NULL CHECK (target_type IN ('ARTICLE', 'CHATTER', 'GUESTBOOK')),
    target_id VARCHAR(180) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users (id),
    parent_id BIGINT REFERENCES comments (id),
    content TEXT NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('VISIBLE', 'HIDDEN', 'DELETED')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX comments_target_status_created_idx
    ON comments (target_type, target_id, status, created_at);
