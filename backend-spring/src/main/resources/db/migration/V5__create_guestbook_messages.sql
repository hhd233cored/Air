-- 留言板与文章评论使用同一套 API DTO，但分别存储，便于理解各自的状态与索引。
CREATE TABLE guestbook_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'VISIBLE'
        CHECK (status IN ('VISIBLE', 'DELETED')),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX guestbook_messages_status_created_idx
    ON guestbook_messages(status, created_at, id);
CREATE INDEX guestbook_messages_user_created_idx
    ON guestbook_messages(user_id, created_at);
